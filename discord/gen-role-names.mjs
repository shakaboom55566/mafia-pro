/* backend/src/role-names.js — role names (ru) for Discord messages (/stats); regenerate after adding roles:
   node discord/gen-role-names.mjs  (discord/test-setup.mjs fails when it is out of date) */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadApp } from './setup.mjs';
export function roleNamesSource() {
  const app = loadApp('ru'); const names = {}; app.ROLES.forEach(r => { names[r.id] = (app.L.roles[r.id] || {}).name || r.id; });
  return '/* generated by discord/gen-role-names.mjs from the app data — do not edit by hand */\nexport const ROLE_NAMES = ' + JSON.stringify(names, null, 0).replace(/,"/g, ', "') + ';\n';
}
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) { fs.writeFileSync(path.join(ROOT, 'backend', 'src', 'role-names.js'), roleNamesSource()); console.log('backend/src/role-names.js written'); }
